import { createContext, useContext, useEffect, useState, useCallback } from 'react'
import { supabase } from '../lib/supabaseClient'
import { clearAllConversations } from '../lib/assistantStore'

const AuthContext = createContext(null)

export function AuthProvider({ children }) {
  const [session, setSession] = useState(null)
  const [user, setUser] = useState(null)
  const [role, setRole] = useState(null)
  const [profile, setProfile] = useState(null)
  const [loading, setLoading] = useState(true)

  // Load the profile row for the current user (includes role, full_name, phone).
  const loadProfile = useCallback(async (userId) => {
    const { data, error } = await supabase
      .from('profiles')
      .select('id, email, full_name, role, phone, patient_code')
      .eq('id', userId)
      .maybeSingle()

    if (error) {
      console.error('Failed to load profile:', error.message)
      return null
    }
    return data
  }, [])

  // Derive role from app metadata (trustworthy) with profile as fallback.
  const refreshUser = useCallback(async () => {
    const { data } = await supabase.auth.getUser()
    const current = data?.user ?? null
    setUser(current)

    if (current) {
      const appRole = current.app_metadata?.role
      if (appRole) {
        setRole(appRole)
      }
      let prof = await loadProfile(current.id)
      // The patient_code is generated by an AFTER INSERT trigger, so it may not
      // be present on the first read right after sign-up. Retry once after a
      // short delay for patients missing it.
      if (prof?.role === 'patient' && !prof?.patient_code) {
        await new Promise((r) => setTimeout(r, 800))
        prof = await loadProfile(current.id)
      }
      setProfile(prof)
      if (!appRole && prof?.role) {
        setRole(prof.role)
      }
    } else {
      setRole(null)
      setProfile(null)
    }
  }, [loadProfile])

  useEffect(() => {
    let mounted = true

    // On mount: fetch existing session if any.
    supabase.auth.getSession().then(({ data }) => {
      if (!mounted) return
      setSession(data.session)
      setRole(data.session?.user?.app_metadata?.role ?? null)
      if (data.session) {
        refreshUser().catch(() => {}).finally(() => setLoading(false))
      } else {
        setLoading(false)
      }
    }).catch((error) => {
      // The saved session could not be read (for example no connection): show
      // the signed-out screens rather than a loader that never ends.
      console.error('Failed to read the session:', error?.message)
      if (mounted) setLoading(false)
    })

    // Listen for auth state changes.
    const { data: sub } = supabase.auth.onAuthStateChange((_event, newSession) => {
      setSession(newSession)
      // The role is inside the signed session (app metadata, set by the server
      // at sign-up). Use it at once; never keep the previous account's role.
      setRole(newSession?.user?.app_metadata?.role ?? null)
      if (newSession) {
        // Wrap async work to avoid deadlock inside the synchronous callback.
        (async () => {
          try {
            await refreshUser()
          } catch (error) {
            console.error('Failed to load the user:', error?.message)
          } finally {
            setLoading(false)
          }
        })()
      } else {
        setUser(null)
        setRole(null)
        setProfile(null)
        setLoading(false)
      }
    })

    return () => {
      mounted = false
      sub.subscription.unsubscribe()
    }
  }, [refreshUser])

  // Sign up a new user with a role.
  const signUp = useCallback(async ({ email, password, fullName, phone, role: signUpRole }) => {
    const { data, error } = await supabase.auth.signUp({
      email,
      password,
      options: {
        data: {
          full_name: fullName,
          phone,
          role: signUpRole,
        },
      },
    })
    return { data, error }
  }, [])

  // Sign in an existing user.
  const signIn = useCallback(async ({ email, password }) => {
    const { data, error } = await supabase.auth.signInWithPassword({ email, password })
    return { data, error }
  }, [])

  // Sign out the current user.
  const signOut = useCallback(async () => {
    await supabase.auth.signOut()
    clearAllConversations() // assistant chats never outlive the session on this device
    setSession(null)
    setUser(null)
    setRole(null)
    setProfile(null)
  }, [])

  // Update the profile fields the user is allowed to edit.
  const updateProfile = useCallback(async (updates) => {
    if (!user) return { error: new Error('Not signed in') }
    const { data, error } = await supabase
      .from('profiles')
      .update(updates)
      .eq('id', user.id)
      .select()
      .maybeSingle()
    if (!error && data) setProfile(data)
    return { data, error }
  }, [user])

  const value = {
    session,
    user,
    role,
    profile,
    loading,
    signUp,
    signIn,
    signOut,
    updateProfile,
    refreshUser,
  }

  return <AuthContext.Provider value={value}>{children}</AuthContext.Provider>
}

export function useAuth() {
  const ctx = useContext(AuthContext)
  if (!ctx) throw new Error('useAuth must be used within an AuthProvider')
  return ctx
}
